// Regenerates lib/gameAbi.js from the compiled RiddleNFTAdvanced artifact.
// Run after `npx hardhat compile` in ../contracts:  npm run generate:abi
import { readFileSync, writeFileSync } from 'node:fs';

const artifact = JSON.parse(readFileSync(
  new URL('../../contracts/artifacts/contracts/nft/RiddleNFTAdvanced.sol/RiddleNFTAdvanced.json', import.meta.url),
));
const FUNCTIONS = new Set([
  'currentSessionId', 'riddleSessions', 'getRiddleSession', 'getCommitRevealState', 'getPlayerCommit',
  'getParticipantData', 'participantData', 'balanceOf', 'tokenOfOwnerByIndex', 'lastActivityTime',
  'REVEAL_WINDOW', 'MIN_SOLVE_TIME', 'mintRiddleAccess', 'commitAnswer', 'revealAnswer',
  'finalizeSession', 'claimPrize',
]);
const EVENTS = new Set(['AnswerCommitted', 'AnswerRevealed', 'SolutionRevealed', 'RiddleCompleted', 'SessionFinalized']);

const abi = artifact.abi.filter((e) =>
  (e.type === 'function' && FUNCTIONS.has(e.name)) ||
  (e.type === 'event' && EVENTS.has(e.name)) ||
  e.type === 'error');

writeFileSync(new URL('../lib/gameAbi.js', import.meta.url),
  `// Generated by scripts/generate-game-abi.mjs from RiddleNFTAdvanced. Do not edit by hand.\n` +
  `export const RIDDLE_GAME_ABI = ${JSON.stringify(abi, null, 2)};\n`);
console.log(`lib/gameAbi.js: ${abi.length} entries`);
