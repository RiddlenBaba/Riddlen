// Regenerates lib/stumpAbi.js from the compiled StumpTheMachine artifact.
// Run after `npx hardhat compile` in ../contracts:  npm run generate:stump-abi
import { readFileSync, writeFileSync } from 'node:fs';

const artifact = JSON.parse(readFileSync(
  new URL('../../contracts/artifacts/contracts/nft/StumpTheMachine.sol/StumpTheMachine.json', import.meta.url),
));
const FUNCTIONS = new Set([
  'challengeCount', 'getChallenge', 'getReveals', 'getEntry', 'owed', 'reserved', 'available',
  'poolByDifficulty', 'entryCostByDifficulty', 'REVEAL_WINDOW', 'MIN_SOLVE_TIME',
  'submit', 'revealAnswer', 'isAccepted', 'MAX_ANSWERS', 'enter', 'sealGuess', 'revealGuess', 'finalize', 'claimRefund', 'withdraw',
]);
const EVENTS = new Set(['ChallengeSubmitted', 'ChallengeOpened', 'ChallengeFinalized', 'GuessRevealed', 'PanelRevealed', 'AuthorRevealed']);

const abi = artifact.abi.filter((e) =>
  (e.type === 'function' && FUNCTIONS.has(e.name)) ||
  (e.type === 'event' && EVENTS.has(e.name)) ||
  e.type === 'error');

writeFileSync(new URL('../lib/stumpAbi.js', import.meta.url),
  `// Generated by scripts/generate-stump-abi.mjs from StumpTheMachine. Do not edit by hand.\n` +
  `export const STUMP_ABI = ${JSON.stringify(abi, null, 2)};\n`);
console.log(`lib/stumpAbi.js: ${abi.length} entries`);
